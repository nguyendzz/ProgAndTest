PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS USERS (
    UserID INTEGER PRIMARY KEY AUTOINCREMENT,
    Username VARCHAR(50) NOT NULL UNIQUE,
    PasswordHash VARCHAR(255) NOT NULL,
    Role VARCHAR(20) NOT NULL CHECK (Role IN ('Admin', 'Staff', 'Lecturer', 'Student')),
    Status VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (Status IN ('Active', 'Locked')),
    Email VARCHAR(100) NOT NULL UNIQUE,
    FailedAttempts INTEGER NOT NULL DEFAULT 0,
    LockedUntil TIMESTAMP NULL,
    ResetToken VARCHAR(128) NULL,
    ResetTokenExpiry TIMESTAMP NULL,
    SessionVersion INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS FACULTIES (
    FacultyID VARCHAR(10) PRIMARY KEY,
    FacultyName VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS CLASSES (
    ClassID VARCHAR(10) PRIMARY KEY,
    FacultyID VARCHAR(10) NOT NULL,
    ClassName VARCHAR(50) NOT NULL,
    AcademicYear VARCHAR(20) NOT NULL,
    FOREIGN KEY (FacultyID) REFERENCES FACULTIES(FacultyID) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS STUDENTS (
    StudentID VARCHAR(10) PRIMARY KEY,
    UserID INTEGER NOT NULL UNIQUE,
    ClassID VARCHAR(10) NOT NULL,
    FullName VARCHAR(100) NOT NULL,
    DOB DATE NOT NULL,
    Email VARCHAR(100) NOT NULL,
    Phone VARCHAR(20),
    Status VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (Status IN ('Active', 'Inactive', 'Graduated', 'Suspended')),
    FOREIGN KEY (UserID) REFERENCES USERS(UserID) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (ClassID) REFERENCES CLASSES(ClassID) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS LECTURERS (
    LecturerID VARCHAR(10) PRIMARY KEY,
    UserID INTEGER NOT NULL UNIQUE,
    FacultyID VARCHAR(10) NOT NULL,
    FullName VARCHAR(100) NOT NULL,
    Email VARCHAR(100) NOT NULL,
    FOREIGN KEY (UserID) REFERENCES USERS(UserID) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (FacultyID) REFERENCES FACULTIES(FacultyID) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS SUBJECTS (
    SubjectID VARCHAR(10) PRIMARY KEY,
    SubjectName VARCHAR(100) NOT NULL,
    Credits INTEGER NOT NULL CHECK (Credits BETWEEN 1 AND 4),
    PrerequisiteID VARCHAR(10) NULL CHECK (PrerequisiteID IS NULL OR PrerequisiteID != SubjectID),
    Status VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (Status IN ('Active', 'Archived')),
    FOREIGN KEY (PrerequisiteID) REFERENCES SUBJECTS(SubjectID) ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS REGISTRATION_PERIODS (
    PeriodID INTEGER PRIMARY KEY AUTOINCREMENT,
    Semester VARCHAR(20) NOT NULL UNIQUE,
    RegOpenDate TIMESTAMP NOT NULL,
    RegCloseDate TIMESTAMP NOT NULL,
    LateRegDeadline TIMESTAMP NULL,
    DropDeadline DATE NOT NULL,
    WithdrawDeadline DATE NOT NULL,
    MinCredits INTEGER NOT NULL DEFAULT 14 CHECK (MinCredits >= 0),
    MaxCredits INTEGER NOT NULL DEFAULT 25 CHECK (MaxCredits >= MinCredits),
    Status VARCHAR(20) NOT NULL DEFAULT 'Upcoming' CHECK (Status IN ('Upcoming', 'Open', 'LateReg', 'Closed'))
);

CREATE TABLE IF NOT EXISTS COURSES (
    SectionID VARCHAR(10) PRIMARY KEY,
    SubjectID VARCHAR(10) NOT NULL,
    LecturerID VARCHAR(10) NOT NULL,
    Semester VARCHAR(20) NOT NULL,
    Capacity INTEGER NOT NULL CHECK (Capacity BETWEEN 10 AND 200),
    DayOfWeek VARCHAR(10) NOT NULL CHECK (DayOfWeek IN ('Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat')),
    StartTime TIME NOT NULL,
    EndTime TIME NOT NULL,
    Room VARCHAR(50) NOT NULL,
    Status VARCHAR(20) NOT NULL DEFAULT 'Open' CHECK (Status IN ('Open', 'Closed', 'Cancelled')),
    FOREIGN KEY (SubjectID) REFERENCES SUBJECTS(SubjectID) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (LecturerID) REFERENCES LECTURERS(LecturerID) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS ENROLLMENTS (
    EnrollmentID INTEGER PRIMARY KEY AUTOINCREMENT,
    StudentID VARCHAR(10) NOT NULL,
    SectionID VARCHAR(10) NOT NULL,
    EnrollDate TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Status VARCHAR(20) NOT NULL DEFAULT 'Enrolled' CHECK (Status IN ('Enrolled', 'Dropped', 'Withdrawn')),
    ConfirmationNumber VARCHAR(30) NOT NULL,
    UNIQUE (StudentID, SectionID),
    FOREIGN KEY (StudentID) REFERENCES STUDENTS(StudentID) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (SectionID) REFERENCES COURSES(SectionID) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS GRADES (
    GradeID INTEGER PRIMARY KEY AUTOINCREMENT,
    EnrollmentID INTEGER NOT NULL UNIQUE,
    AttendanceScore DECIMAL(3,1) NULL CHECK (AttendanceScore IS NULL OR (AttendanceScore >= 0.0 AND AttendanceScore <= 10.0)),
    MidtermScore DECIMAL(3,1) NULL CHECK (MidtermScore IS NULL OR (MidtermScore >= 0.0 AND MidtermScore <= 10.0)),
    FinalExamScore DECIMAL(3,1) NULL CHECK (FinalExamScore IS NULL OR (FinalExamScore >= 0.0 AND FinalExamScore <= 10.0)),
    FinalScore DECIMAL(3,1) NULL CHECK (FinalScore IS NULL OR (FinalScore >= 0.0 AND FinalScore <= 10.0)),
    GradeStatus VARCHAR(10) NOT NULL DEFAULT 'Draft' CHECK (GradeStatus IN ('Draft', 'Final', 'W')),
    FOREIGN KEY (EnrollmentID) REFERENCES ENROLLMENTS(EnrollmentID) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS REGISTRATION_CART (
    CartID INTEGER PRIMARY KEY AUTOINCREMENT,
    StudentID VARCHAR(10) NOT NULL,
    SectionID VARCHAR(10) NOT NULL,
    AddedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Status VARCHAR(20) NOT NULL DEFAULT 'InCart' CHECK (Status IN ('InCart', 'Confirmed', 'Expired')),
    UNIQUE (StudentID, SectionID),
    FOREIGN KEY (StudentID) REFERENCES STUDENTS(StudentID) ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (SectionID) REFERENCES COURSES(SectionID) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS WAITLIST (
    WaitlistID INTEGER PRIMARY KEY AUTOINCREMENT,
    StudentID VARCHAR(10) NOT NULL,
    SectionID VARCHAR(10) NOT NULL,
    QueuePosition INTEGER NOT NULL CHECK (QueuePosition >= 1),
    JoinedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Status VARCHAR(20) NOT NULL DEFAULT 'Waiting' CHECK (Status IN ('Waiting', 'Enrolled', 'Skipped', 'Cancelled')),
    UNIQUE (StudentID, SectionID),
    FOREIGN KEY (StudentID) REFERENCES STUDENTS(StudentID) ON UPDATE CASCADE ON DELETE CASCADE,
    FOREIGN KEY (SectionID) REFERENCES COURSES(SectionID) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS SEMESTER_REGISTRATIONS (
    RegID INTEGER PRIMARY KEY AUTOINCREMENT,
    StudentID VARCHAR(10) NOT NULL,
    Semester VARCHAR(20) NOT NULL,
    TotalCreditsEnrolled INTEGER NOT NULL DEFAULT 0 CHECK (TotalCreditsEnrolled >= 0),
    ConfirmationNumber VARCHAR(30) NOT NULL UNIQUE,
    UNIQUE (StudentID, Semester),
    FOREIGN KEY (StudentID) REFERENCES STUDENTS(StudentID) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TRIGGER IF NOT EXISTS trg_grades_compute_insert
AFTER INSERT ON GRADES
WHEN NEW.AttendanceScore IS NOT NULL AND NEW.MidtermScore IS NOT NULL AND NEW.FinalExamScore IS NOT NULL AND NEW.GradeStatus != 'W'
BEGIN
    UPDATE GRADES
    SET FinalScore = ROUND((NEW.AttendanceScore * 10 + NEW.MidtermScore * 30 + NEW.FinalExamScore * 60 + 0.000001) / 100.0, 1)
    WHERE GradeID = NEW.GradeID;
END;

CREATE TRIGGER IF NOT EXISTS trg_grades_compute_update
AFTER UPDATE OF AttendanceScore, MidtermScore, FinalExamScore ON GRADES
WHEN NEW.AttendanceScore IS NOT NULL AND NEW.MidtermScore IS NOT NULL AND NEW.FinalExamScore IS NOT NULL AND NEW.GradeStatus != 'W'
BEGIN
    UPDATE GRADES
    SET FinalScore = ROUND((NEW.AttendanceScore * 10 + NEW.MidtermScore * 30 + NEW.FinalExamScore * 60 + 0.000001) / 100.0, 1)
    WHERE GradeID = NEW.GradeID;
END;
